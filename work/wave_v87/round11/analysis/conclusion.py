"""第十一段階の全件分解から、主案と反証の短い結論を保存する。"""
from pathlib import Path
import json
import pickle

HERE=Path(__file__).resolve().parent


def main():
    """
    機能: 保存済み全件解析を短く整理し、結果で新たな主案を選び直さない。
    引数: なし。
    返り値: None。日本語JSONへ保存する。
    """
    full=json.loads((HERE/'相手GUの入口見送りと途中縮小の全親分解.json').read_text(encoding='utf-8'))
    pairs={(x['元ID'],x['変更ID']):x for x in full['比較']}
    chosen=[('P_E0_H0','P_E1_H0'),('P_E1_H0','P_E1_H1'),('P_E0_H0','P_E0_H1'),('P_E0_H0','P_E0_H2')]
    keys=['変更活動親','改善親','悪化親','元赤字親の改善額','元黒字親の取り逃し額',
        '元黒字親の上積み額','元赤字親の悪化額','料金前差','料金差','収支差']
    values=[dict(元ID=a,変更ID=b,全30={s:{k:pairs[a,b]['期間']['全30'][s][k] for k in keys}
        for s in ('TOPIX','NK225')}) for a,b in chosen]
    books=pickle.loads((HERE.parent/'observed/ledgers/P_E0_H0.pkl').read_bytes())
    gate={s:dict(同方向=0,空玉=0,反対方向=0,参照不能又は古い=0) for s in ('TOPIX','NK225')}
    for key,book in books.items():
        for e in book['peer_events']:
            if e[1]!=1:continue
            label='参照不能又は古い' if e[4]<0 or e[16]>180 else ('空玉' if e[7]==0 else ('同方向' if e[7]*e[3]>0 else '反対方向'))
            gate[key[1]][label]+=1
    out=dict(結論='相手GUの同方向保有はTOPIXの損益比と最大下落を改善したが、NK225では後半赤字。相手の負け停止に連動した半減を重ねても、両銘柄共通の安定改善にはならなかった。',
        固定主案='P_E1_H1を別条件へ差し替えない。',
        主案全30=full['全条件期間']['P_E1_H1']['全30'],主案後14=full['全条件期間']['P_E1_H1']['後14'],
        入口の意味=gate,
        原因=[
            'E1入口の拒否は、TOPIX75件のうち74件、NK22593件のうち87件が相手GUの空玉。相手が逆方向と判断した証拠と、相手がまだ建てていないことは同じではない。',
            'E1はTOPIXで旧赤字767,476円を避ける一方、旧黒字795,163円も捨てた。NK225は旧赤字413,660円の回避に対し旧黒字578,500円を失った。',
            'E1H0からH1への変更は、TOPIX16組発火のうち11組改善・5組悪化。旧負け44,011円の改善より旧勝ち87,995円の喪失が大きい。NK225は8組発火で7組改善・1組悪化だが、1組の8,200円喪失が他の6,300円改善を超えた。',
            '主案のH1差額はTOPIX−43,984円・NK225−1,900円。料金差は−16円・0円なので主因は返済後の価格露出を減らした影響である。',
            'E1H1の途中部品は前半には両商品で改善したが、後半はTOPIX−69,992円・NK225−4,700円。前半だけの成功から安定部品とはいえない。',
            '入口を制限しないE0へH1又はH2を加えるとNK225は改善したが、TOPIXは悪化した。相手損切りが自己の継続可否を必ず示すという規則は両商品で共通しなかった。'],
        部品差分=values,
        通知の限界='相手の損切りは相手の建値・ATR・残玉・注文線に依存する。この保存経路では自己も負けが拡大する例と、自己だけ後に回復する例が両方あった。通知を一般的な市場反転と同一視しない。',
        少数例='E3はTOPIX19親・NK22518親。全30でもNK225赤字。前半TOPIXの79.9899%は表示を丸めると80%になるが、厳密には80%未達で、8親の少数観測。',
        具体例=[x for x in full['具体例'] if x['変更ID']=='P_E1_H1'],
        検算='全源GU不変。同じEのH0/H1/H2は初回実新規が完全同一。入口H0の採用親は経路不変。全元親の0円対応と料金前差−料金差が全差額に一致。',
        データ制約='全30場は既知。選んだ数例でなく全親を集計。次観測が同じ代理時計の場合もあり、通信遅延ゼロを意味しない。')
    (HERE/'相手GUの当時情報が改善した範囲と失敗の短い結論.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('入口と途中を分けた短い結論を保存',flush=True)


if __name__=='__main__':main()
