def catalog():
    """
    機能: 元GU対照と入口四種・途中三種を事前固定する。
    引数: なし。
    返り値: list[dict]。E3はE2の非負条件を要求しない。
    """
    base=dict(mask=1,time_mode='U',changes={},source_round=85,source_id='E01_G_U')
    out=[dict(base,id='P_GU_IDEAL',name='元GU・追加観測待ちなし',execution_mode='IDEAL',entry_mode=0,holding_mode=0)]
    entries=['相手による入口制限なし','相手元GUも同方向保有','相手同方向・当時清算収支非負','相手同方向・当時順行0.25ATR以上']
    holds=['元の返済に従う','相手負け通知で残枚数の半分切上げ','相手負け通知で全返済']
    for e in range(4):
        for h in range(3):
            out.append(dict(base,id=f'P_E{e}_H{h}',name=entries[e]+'・'+holds[h],execution_mode='P',entry_mode=e,holding_mode=h))
    assert len(out)==13
    return out


