"""支持強度の診断を既検証との重複、反例、次の反証条件へまとめる。"""

import gzip
import json

from risk_structure import ROOT, HERE, read, sha


def main():
    """
    機能: 旧台帳と診断集計だけから、強い支持仮説の成立範囲を保存する。
    引数: なし。
    返り値: None。結論JSONを保存する。新たな売買再生や最適閾値探索は行わない。
    """
    source = HERE/'入口支持強度と既存親組の診断.json'
    diagnosis = read(source)
    evidence = []
    for filename in ['work/wave_v27/adversarial/H019__D023.json.gz',
                     'work/wave_v28/adversarial/H019__J112.json.gz']:
        path = ROOT/filename
        with gzip.open(path, 'rt', encoding='utf-8') as stream:
            prior = json.load(stream)
        cases = []
        for case in prior['cases']:
            if 'CONFIRMATION' in case['case']:
                cases.append(dict(ID=case['case'],
                                  TOPIX収支=case['symbols']['TOPIX']['net_yen'],
                                  NK225収支=case['symbols']['NK225']['net_yen']))
        evidence.append(dict(参照=filename, SHA256=sha(path), 元ID=prior['candidate']['id'],
                             条件='.05ATRの0.8倍/1.2倍、すなわち.04/.06ATR。元の支持保持時間は変えない。',
                             実再生=cases,
                             比較制約='旧13セッション・旧管理と枚数。現在のGU/T2_P1や手数料条件との同値比較ではない。'))
    tables = []
    for item in diagnosis['集計']:
        if item['期間'] != '全30':
            continue
        bands = []
        for name, group in item['固定区分']['最新支持区分'].items():
            account = group['既存親組']
            if account['組数']:
                bands.append(dict(最新支持=name, 組数=account['組数'], 勝組=account['勝組'],
                                  旧組の収支=account['収支'], 平均勝負比=account['平均勝負比'],
                                  T2目安075到達組=group['保護目安075到達組'],
                                  初期ATR中央値=group['固定初期ATR分布_過去']['p50'],
                                  中値差の呼値中央値=group['最新中値差呼値分布_過去']['p50']))
        tables.append(dict(手法=item['手法'], 銘柄=item['銘柄'], 区分=bands,
                           閾値半呼値未満=item['現閾値が半呼値未満の組'],
                           全組数=item['全組']['既存親組']['組数']))
    output = dict(
        結論='弱い30秒支持を高い順行確率と読み替える根拠は不足していた。ただし閾値を上げれば解決するとも言えない。保有・再参加・呼値の影響を分離する必要がある。',
        実施='原GU 278組とT2_P1 818組の既存約定を、約定直前までに公開済みの支持へ照合。新戦略損益の計算はしていない。',
        根拠=[
            'T2_P1の最新支持.05超.25以下は両商品で赤字、.25超.75以下は旧組の部分集合では両商品黒字。ただし入口見送りで後続の準備と通常影時計も変わるため、閾値変更後の収支ではない。',
            'NKの.75超は6組中2勝、合計−7,320円。強さと成果は単調でなく、極端に強い直前変化を万能条件にできない。TOPには当該強度の現存入口がなく比較不能。',
            '後14のNK .25超.75以下は19/29勝で+19,620円だが平均勝負比0.676。黒字の部分集合でも一勝より一敗が大きく、損小利大の要件には足りない。',
            '元GUは最新支持が0以下の組でもTOP+343,790円、NK+16,220円。短期支持の消失は必ずしも中期方向の失敗ではない。全ての短期失効で一律に見送る対策は勝ちを失う可能性がある。',
            'T2_P1では閾値.05ATRが半呼値未満だった入口がTOP356/423、NK316/395。倍率の微変更が板中値の実際の刻みを越えない場合は判定自体が変わらない。',
            '最新支持.05〜.25帯と.25〜.75帯の実中値差中央値は両商品とも1呼値と2呼値。一方で強め帯の固定ATRは小さい。正規化値の上昇には値動き増と分母低下の両方が含まれる。',
        ],
        損益機構=[
            'T2は.75ATR順行で幅.5ATRの追尾が始まる。ちょうど始動直後に戻れば、理想連続価格で最初に守る幅は約.25ATR。一方初期停止は.75ATRである。',
            '毎回ちょうど+.25か−.75で終わる単純二点モデルなら費用前の損益分岐勝率は75%。これは実戦略の勝率必要条件ではなく、最小確保と初期損失の非対称を示す例。実際の大勝ち、丸め、部分決済、料金により分布は異なる。',
            '支持閾値の.05ATRは既に起きた30秒変化で、将来の利幅ではない。保護始動まで15倍必要という比較だけで理論的破綻や必要倍率を決めることはできない。',
            'TOPIXの1呼値は.5pt、片道料相当は.0418pt。NKは10円、片道料相当1.1円。往復だけなら.0836ptと2.2円だが、実行時の気配差・飛びは別である。支持の過去変化とこれらを比べても、将来の利益を確保したことにはならない。',
        ],
        次段階に必要な反証=[
            '強度を変える場合は、既に旧組の条件付き収支を見た探索として事前固定する。今回の後14を未知検証とは呼ばない。最良となる閾値を細かく探してから有意としない。',
            '元の.05と、入口幅.25など既存の機械幅に由来する少数の対照を固定し、最新支持を要求する変更と強度だけを変える変更を分ける。両方を同時に変えると原因が判別できない。',
            'ATR倍率と実呼値数を併記し、同じ支持値でも低ATRだけで強判定になった例を分ける。費用・呼値に満たない利益保護幅を勝率だけで正当化しない。',
            '全30を時計ごと再生し、除けた負け、失った勝ち、代わりに生じた新規を別集計する。旧台帳の負けだけを削る再集計では不十分。',
            '初期停止前に保護目安へ届く確率だけでなく、料金後平均勝負比・最大赤字場・最大下落・日夜・前後期で判定する。取引減だけを精度改善とは呼ばない。',
        ],
        既検証=[
            dict(項目='同じ短期支持閾値の微変更', 状態='実再生済み', 資料=evidence,
                 注意='強度確認の考えそのものは新しくない。今回の強度を大幅に変えたGU/T2_P1の全再生は本診断では行っていない。'),
            dict(項目='閾値と呼値の量子化', 状態='診断済み',
                 参照='work/wave_v27/entry_threshold_ticks.json',
                 条件='全26入力、.05/.10ATR×.8/1/1.2。半呼値と1呼値の未満割合を区別。成績選抜に不使用。'),
            dict(項目='30秒窓の変更', 状態='v47で既検証、閾値強度とは別',
                 参照='work/wave_v47/component_signals.py',
                 条件='short_scale .8/1/1.2は24/30/36秒窓。元.05ATR閾値を5倍にする比較ではない。'),
            dict(項目='短時間の強い傾き', 状態='v66で別入口の探索済み',
                 参照='work/wave_v66/report.py',
                 条件='価格速度・効率・加速・突破による順逆336条件。今回のE01支持閾値だけの変更とは異なる。',
                 注意='短期の強さを増せば両商品で利益になる一般則は得ていない。異なる約定・保有条件の成績を今回に直接移植しない。'),
        ],
        簡約表=tables, 根拠診断SHA256=sha(source),
        未検証='本診断の支持強度を注文条件として使った新戦略の全経路・新規機会・実損益。新しい最適閾値は選んでいない。')
    destination = HERE/'支持の弱さ仮説の結論と既検証.json'
    destination.write_text(json.dumps(output, ensure_ascii=False, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    print(str(destination))


if __name__ == '__main__':
    main()
