def equality_checks():
    """
    機能: 指定線約定における極値停止と固定0.5ATR停止の代数的同値を検査する。
    引数: なし。
    返り値: dict。実価格経路・実験損益を使わない算術例。
    """
    equal = 0
    for tick, extreme in ((.5, 4075.), (10., 65500.)):
        for atr in [tick*x/7. for x in range(1, 141)]:
            width = max(tick, .5*atr)
            for core_side in (1, -1):
                raw = extreme-core_side*width
                entry = (math.floor(raw/tick+1e-9) if core_side > 0 else math.ceil(raw/tick-1e-9))*tick
                raw_stop = entry+core_side*width
                fixed = (math.ceil(raw_stop/tick-1e-9) if core_side > 0 else math.floor(raw_stop/tick+1e-9))*tick
                assert abs(fixed-extreme) < 1e-8
                equal += 1
    return dict(比較数=equal, 全一致=True,
        仮定='過去極値が呼値上。保険は極値から0.5ATR逆行した呼値丸め指定線で約定。幅は最低1呼値。',
        帰結='この条件下ではS1過去極値停止とS3建値固定0.5ATR停止は同値。S2はそこから元玉方向へ1呼値外。',
        限界='支持待ちの既通過成行や観測飛びで建値が変われば同値とは限らない。これは新PL再生ではない。')


