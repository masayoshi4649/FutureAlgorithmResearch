def fee(quantity, unit):
    """
    機能: 1注文の数量に片道料金を掛け、1円未満を切り捨てる。
    引数: quantity(int)は非負数量、unit(str)は片道料金。
    返り値: intの注文料金。
    """
    return int((Decimal(quantity) * Decimal(unit)).to_integral_value(rounding=ROUND_FLOOR))


def arithmetic_checks():
    """
    機能: 合成数量だけで差引実行の現金、時価、料金差の恒等式を確認する。
    引数: なし。実相場、旧結果、新しい売買条件を読み込まない。
    返り値: dictの確認件数と説明用の算術例。
    """
    count = 0
    for unit, value, cap in [('41.8', 1000, 10), ('11', 10, 20)]:
        for buy in range(cap + 1):
            for sell in range(cap + 1):
                for price in [100, 101, 105]:
                    signed = buy - sell
                    original_cash = -buy * price * value + sell * price * value
                    mapped_cash = -signed * price * value
                    assert original_cash == mapped_cash
                    original_fee = fee(buy, unit) + fee(sell, unit)
                    mapped_fee = fee(abs(signed), unit)
                    for mark in [99, 100, 106]:
                        original = original_cash + signed * mark * value - original_fee
                        mapped = mapped_cash + signed * mark * value - mapped_fee
                        assert mapped - original == original_fee - mapped_fee
                        count += 1
    # ----------------------------------------
    # 同方向の合算には相殺がない。切捨て位置が変わり、料金が増す反例も残す。
    assert fee(2, '41.8') + fee(3, '41.8') == 208
    assert fee(5, '41.8') == 209
    examples = [
        {'場面': 'TOPIX同方向2枚と3枚を1注文へ', '元注文料金': 208, '差引注文料金': 209, '削減額': -1},
        {'場面': 'TOPIX買い5枚と売り5枚が同じ行で相殺', '元注文料金': 418, '差引注文料金': 0, '削減額': 418},
        {'場面': 'NK買い10枚と売り10枚が同じ行で相殺', '元注文料金': 220, '差引注文料金': 0, '削減額': 220},
        {'場面': 'TOPIX買い5枚と売り3枚を買い2枚へ', '元注文料金': 334, '差引注文料金': 83, '削減額': 251},
    ]
    # ----------------------------------------
    # 元の保険を次観測まで持つ時価と、コア終了行で実玉をなくす時価の差。
    bridge = []
    for core_side in [-1, 1]:
        for later_price in [99, 100, 101]:
            hedge = -core_side * 5
            old_gain = hedge * (later_price - 100) * 1000
            earlier_flat_gain = 0
            assert earlier_flat_gain - old_gain == -hedge * (later_price - 100) * 1000
            bridge.append({'コア方向': core_side, '旧保険符号付き枚数': hedge,
                           '終了行価格': 100, '次観測価格': later_price,
                           '早期清算引く従来の料金前差': -old_gain})
    return {'価格経路不使用': True, '同時現金時価の恒等式確認件数': count,
            '一観測露出の差の確認件数': len(bridge), '料金例': examples, '一観測露出の反例': bridge}


