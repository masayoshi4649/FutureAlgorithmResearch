"""会計と部品対照を短い結論へまとめ、改善と黒字達成を区別する。"""

from diagnose import HERE,read,save


def main():
    """
    機能: 固定主仮説の結果と停止短縮の反例を表示用に保存する。
    引数: なし。
    返り値: None。推奨候補を結果から差し替えない。
    """
    data=read(HERE/'全12条件の改善と旧勝ち取り逃し分解.json')
    models={}
    for name,block in data['モデル別'].items():
        main=next(v for v in block['全12条件'] if v['条件']=='R3_S50')
        both=[v['条件'] for v in block['全12条件'] if all(v['期間別']['全30'][s]['集計']['net']>0 for s in ('TOPIX','NK225'))]
        models[name]=dict(両商品全30黒字条件=both,主仮説=main)
    pairs=data['モデル別']['observed']['部品を揃えた比較']
    stopping=[v for v in pairs if v['元']=='R0_S75' and v['改修']=='R0_S50' and v['期間']=='全30']
    save('全12改修の独立解釈.json',dict(
        結論=[
            '同じEMA支持中の再参加を抑えると損失は減ったが、主仮説R3_S50は観測価格でTOPIX赤字・日経の小幅黒字にとどまり、全日安定した共通解は未達。',
            '観測価格の12条件で両商品全30黒字は0。指定線どおり約定する対照では両黒字があり、実約定の条件差を無視して結論を混ぜない。',
            '別周期だけを待つR1_S75ではTOPIXは前半・後半とも黒字だが、日経前半は赤字。高安再突破だけのR2_S75はTOPIXの収支・最大下落を悪化させた。高値更新や厳しい確認を足せば一律に良くなるわけではない。',
            '停止を0.75から0.5ATRへ短くした同入口の元黒字組では、TOPIX31組・日経28組が赤字へ変わった。被害の縮小と、途中逆行を越えて伸びる利益の放棄が同時に起きている。',
            '主仮説の原P1比の改善は最大改善1場を除いても残る。ただし主仮説自体の全30収支から最大利益1場を除くと両商品が赤字になる。赤字削減と安定収益は別である。'],
        モデル別=models,
        初期停止短縮の同条件対照=stopping,
        会計監査=read(HERE/'全12条件の独立会計と再参加条件.json'),
        制約='既知30場の改修探索。前16と後14を分けたことを未知将来の検証とは呼ばない。売りだけを事後選抜した新アルゴリズムは作っていない。'))


if __name__=='__main__':
    main()
