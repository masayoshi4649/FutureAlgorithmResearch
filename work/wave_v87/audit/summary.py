"""独立に追跡した再参加損失を、説明用の短い根拠へまとめる。"""

import math
from diagnose import HERE, read, save


def main():
    """
    機能: 全追加組の傾向と反例、原本照合済み代表例を保存する。
    引数: なし。
    返り値: None。改善条件の損益や将来を使った取引判定は計算しない。
    """
    source=read(HERE/'再参加悪化6口座と全追加取引.json')
    raw=read(HERE/'代表追加赤字の生板小窓と照合.json')
    snapshots={(c['セッション'],c['商品'],r['原本0始まり行']):r
        for c in raw['原本小窓'] for r in c['小窓']}
    all_trades=[d for c in source['ケース'] for d in c['全追加取引']]
    direct=[d for d in all_trades if d['前回との比較']['前回が黒字早期再参加許可']]
    same=[d for d in direct if d['前回との比較']['前回方向と同じ']]
    losing=[d for d in all_trades if d['収支']<0]
    stale=[d for d in all_trades if not d['当時の根拠']['約定時']['両市場G成立']]
    assert all(d['当時の根拠']['約定直前観測']['両市場G成立'] for d in stale)
    selected=[]
    for c in source['ケース']:
        candidates=[d for d in c['全追加取引'] if d['収支']<0
            and d['前回との比較']['前回が黒字早期再参加許可']]
        d=min(candidates,key=lambda x:x['収支'])
        snap=snapshots[(c['セッション'],c['商品'],d['新規']['原本0始まり行'])]
        old=d['前回との比較']; path=d['事後推移']
        selected.append(dict(セッション=c['セッション'],商品=c['商品'],親組=d['親組'],
            新規時刻=d['新規']['時刻'],方向=d['方向'],枚数=d['新規枚数'],建値=d['新規価格'],
            原本1始まり行=d['新規']['原本1始まり行'],買気配=snap['買板'][0],売気配=snap['売板'][0],
            前回全返済時刻=old['前回全返済']['時刻'],前回全返済価格=old['前回全返済']['現在値'],
            前回収支=old['前回収支'],前回高値=old['前回高値']['現在値'],前回安値=old['前回安値']['現在値'],
            前回順行極値から新規の順方向差=old['前回順行極値から新規の順方向差'],
            再参加まで秒=old['前回全返済から新規秒'],初期ATR=d['初期ATR'],
            初期損切り指定線=d['初期損切り指定線'],初期損切り幅=d['丸め後初期損切り幅'],
            最大順行=path['最大順行'],最大不利=path['最大不利'],
            全返済時刻=d['全返済']['時刻'],全返済価格=d['全返済']['現在値'],返済理由=d['返済理由'],
            収支=d['収支'],手数料=d['手数料'],
            両EMA足更新=old['新準備で自己公開足が更新'] and old['新準備で相手公開足が更新'],
            前回全返済から新準備までG継続=old['前回全返済から新準備までG継続']))
    totals={}
    for symbol in ('TOPIX','NK225'):
        cases=[c for c in source['ケース'] if c['商品']==symbol]
        delta=math.fsum(c['差額'] for c in cases)
        fees=math.fsum(c['新手数料']-c['元手数料'] for c in cases)
        totals[symbol]=dict(上位3場の収支悪化=delta,手数料増=fees,手数料前の損益悪化=delta+fees,
            追加黒字=math.fsum(c['差額分解']['追加黒字'] for c in cases),
            追加赤字=math.fsum(c['差額分解']['追加赤字'] for c in cases),
            消えた元取引による差額=math.fsum(c['差額分解']['消えた元取引の差額'] for c in cases))
    save('独立原因監査の結論.json',dict(
        対象='T2_SとT2_P1の差が最も悪化した商品別3場、合計6口座。悪い場を選んだ事後診断なので全市場の出現率には一般化しない。',
        主結論=[
            '元と同じ入口の親組は6口座すべて損益不変。高速再参加で追加した損失と、それによって後続経路が変わり元の黒字入口を失った分が悪化を説明する。',
            '入口では新しい両市場EMA足を読んでいた。それでも同方向の支持が残る間に小反発・小反落ごとに参加し、前の波の途中や終盤で初期損切りに至った。更新済み情報と新しい有利な機会は同じではない。',
            '前回高安の内側への再参加は損失例に多い。ただし日経9/22夜18:54:55の買いは前高値を越え、同調も崩れて再成立した後だったが、順行0円で80円逆行した。高安更新・再同調だけで必勝とは言えない。',
            '料金増だけでは説明できず、上位3場では両商品とも損益悪化の大半が手数料前に起きた。',
            '約定時にGが崩れた4組も確認したが、直前の保存観測ではG成立。次観測までの間隔中に新しい指標が公開され、前行注文が約定したケースであり、未来の指標で先に取消すと別の先取りになる。',
            '原本の板価格・数量は確認したが、注文IDや真の受信時計はない。焦り・大口の意図・補充と取消の内訳は観測していない。'],
        数値根拠=dict(全追加組数=len(all_trades),全追加赤字組数=len(losing),
            前回黒字直後の追加組数=len(direct),そのうち同方向=len(same),
            同方向直後かつ前回極値未更新=sum(d['前回との比較']['前回順行極値から新規の順方向差']<=0 for d in same),
            同方向直後かつG途切れなし=sum(d['前回との比較']['前回全返済から新準備までG継続'] for d in same),
            全追加で新準備時に両EMA更新=sum(d['前回との比較']['新準備で自己公開足が更新'] and d['前回との比較']['新準備で相手公開足が更新'] for d in all_trades),
            約定時G不成立=len(stale),そのうち直前観測G成立=len(stale),商品別悪化分解=totals),
        代表6例=selected,
        約定時支持消失=[dict(セッション=d['セッション'],商品=d['商品'],親組=d['親組'],
            約定=d['新規'],収支=d['収支'],直前観測=d['当時の根拠']['約定直前観測']['観測'],
            直前からの間隔=d['事後推移']['約定直前からの観測間隔秒']) for d in stale],
        改善の機構=[dict(案='同方向への再参加は別の同調周期を待つ',
            条件='黒字全返済後、観測可能な両市場EMA支持が有効情報で一旦外れ、両側の新しい公開足で同方向へ戻ってから新準備する。欠測を支持消失と数えない。',
            狙い='長い支持状態の同じ波を短いトレールで何回も買い直す動きを抑える。',
            反証='同調再成立後も負けた例があり、有望な継続波の取り直しを失う。条件全体を再生して確かめる必要がある。'),
            dict(案='同方向再参加には前の実建玉の極値更新を要求する',
            条件='前回返済までに分かった最高値・最安値だけを保存し、買いは前高値＋1呼値、売りは前安値−1呼値と入口トレールの厳しい方で待つ。',
            狙い='既に取った価格帯内の小さな揺れを新しい波と数えにくくする。',
            反証='前高値更新直後に反落した日経例があり、ブレイクを買う分だけ建値悪化もあり得る。')],
        実装確認=dict(同入口損益差全6口座ゼロ=True,原本価格時計照合=raw['現在値と時計の一致行数'],
            原本指紋不変=raw['既存指紋と原本SHA256一致ファイル数'],
            既存実装監査='v86の全3600口座会計・人工71条件・未来切断558地点に今回の原本と同入口照合を追加。今回、新たな会計誤りや未来参照は確認していない。'),
        制約='保存されたCurrentPriceで約定した仮想成績。板気配と異なる現在値約定を実際に保証するものではなく、今回の会計に気配差損を後付けしていない。'))
    print('原因監査要約',len(all_trades),len(losing),totals)


if __name__=='__main__':
    main()
