        零幅='d=0も紙上建値の有利側丸め線への指値。無条件次観測成行とは別の条件。',
        約定='買いは観測CurrentPrice<=指値、売りは>=指値で、その観測CurrentPriceを実約定値とする。過去の指値線そのもので約定した扱いにしない。',
        枚数='一親一回だけ初回TOPIXmini5枚・NK225micro10枚。片方向上限10枚・20枚。',
