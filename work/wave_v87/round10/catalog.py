"""仮想方向判断を変えず、実両建て・差引・元玉終了後抑止を比較する。"""


def catalog():
    """
    機能: 四つの固定仮想戦略と三つの実行層、および元GU理想対照を返す。
    引数: なし。
    返り値: list[dict]。十三条件を後半成績によって選び直さない。
    """
    base=dict(mask=1,time_mode='U',changes={},source_id='E01_G_U',source_round=85,execution_mode='IDEAL')
    out=[dict(base,id='GU_IDEAL',name='元GU・追加観測待ちなしの観測価格対照')]
    for source,stage,label in (('GU',85,'元GU'),('C_H05_S25',7,'順行0.5・反対保険停止0.25'),
            ('C_H05_S50',7,'順行0.5・反対保険停止0.5'),('I_P00_R50_C1',8,'極値から0.5逆行・双方反対支持')):
        for mode,description in (('G','次観測の実両建て'),('N','次観測の差引枚数'),('F','差引・元玉終了後を抑止')):
            out.append(dict(base,id=source+'_'+mode,name=label+'・'+description,
                source_id='E01_G_U' if source=='GU' else source,source_round=stage,execution_mode=mode))
    assert len(out)==13
    return out


