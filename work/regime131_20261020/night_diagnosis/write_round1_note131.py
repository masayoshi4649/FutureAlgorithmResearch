"""保存診断の実値だけから、次巡の理由と反証例を短い説明へまとめる。"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def money(value):
    """
    機能: 正負付きの金額を整形する。
    引数: value(float)は円。
    返り値: strは金額。
    """
    return format(value, "+,.0f")+"円"


def main():
    """
    機能: 全親診断から件数・損失上位三場・具体時刻を抜粋する。
    引数: なし。
    返り値: None。新しいMarkdownだけを保存する。
    """
    data = json.loads((HERE / "第一巡の夜間入口と順行反復の全親診断.json").read_text(encoding="utf-8"))
    lines = [
        "# 第一巡夜間：損失はどこで生じたか",
        "",
        "全21夜間、R01・R05・R09の両商品、計1,245親を調べた。金融再生は0。"
        "全1,032口座の独立会計は一致し、全場参加も達成した。赤字は会計不整合ではない。",
        "",
        "TOPIXはミニ5枚、日経はマイクロ10枚。以下は手数料後。"
        "R01は常に追随、R05は時計で追随/回帰を切替、R09は時計と方向効率で切替。",
        "",
        "## 入口別",
        "",
        "|手法|商品|追随80：親数/収支|回帰81：親数/収支|期限82：親数/収支|夜間合計|",
        "|---|---|---:|---:|---:|---:|",
    ]
    for g in data["groups"]:
        cells = []
        for reason in ("80", "81", "82"):
            r = g["groups"]["entry_reason"].get(reason, {"parents": 0, "net": 0})
            cells.append(str(r["parents"])+" / "+money(r["net"]))
        lines.append("|"+g["method"]+"|"+g["symbol"]+"|"+"|".join(cells)+"|"+money(g["all"]["net"])+"|")
    lines += [
        "",
        "**期限参加だけを直しても足りない。** 通常の追随・回帰も両商品で赤字だった。",
        "",
        "## 三段階の原因",
        "",
        "1. **直接の損失**：入口の方向へほぼ進まず損切り、又は少し順行した後に初期ストップまで戻った。"
        "R05 TOPIXの113敗中70敗は最大順行0.25R未満で、損失1,274,260円。"
        "残り43敗は0.25R以上1R未満までは進んだが、損失967,974円。"
        "R09 日経も112敗中75敗が0.25R未満、661,500円の損失。",
        "2. **注文法の原因**：入口は追跡極値から0.25Rの反発で発火するが、退出は建値から1Rの損切り。"
        "入口を作った反発が崩れても、1Rまで損失を許す。利益保護も1R順行まで始まらない。"
        "ただし1R到達後が勝ちになるのは出口設計の結果であり、『1R到達を事前に予測できた』証拠ではない。",
        "3. **選択の原因**：低い方向効率を回帰の証拠として扱い、単なる動き始め・急反転も回帰に分類する。"
        "期限参加は選択済み状態にかかわらず追随として建てる。方向の合議だけでは、"
        "反発の余地や、反発を否定する価格が注文へ結びついていない。",
        "",
        "気配の負担も大きい。R05 TOPIXは実気配による粗損益−415,000円、"
        "新規/返済時点の半スプレッド合計736,250円。R09 日経はそれぞれ−180,000円/306,000円。"
        "同じ売買時刻を中値評価すれば+321,250円/+126,000円になるが、**中値での約定は実現した成績ではない**。"
        "判断から次正常行への約定差は、それぞれ47,500円/38,000円有利だった。今回は遅延悪化が主因ではない。",
        "",
        "## 具体例：判断時点の画像も確認",
        "",
        "- **9/25 TOPIX、R05親0**：17:45:05に4124買い、19:32:50に4115返済、−45,418円。"
        "途中6pt進んだが初期幅8.67ptに届かず保護未開始。"
        "判断時までの図では二市場とも上昇しており、この時点で後の下落を知ることはできない。"
        "18時頃の上昇停止後に入口の根拠を更新せず、下落を初期幅まで抱えたのが出口側の問題。",
        "- **10/2 日経、R09親0**：17:45:00に69170売り、17:54:42に69310返済、−14,220円。"
        "直前の20分方向効率は0.0278。両市場は上下を繰り返していたが、期限到来で追随売りになった。"
        "無取引回避と追随判断を一体化している。",
        "- **10/2 日経、R09親6→7**：23:08:10に70060売り、23:09:36に70190返済、−13,220円。"
        "次は23:19:58に70160買い、23:45:04に70040返済、−12,220円。"
        "二市場の強い上昇途中の小戻りを回帰売り、その後の高値付近を追随買いにして往復損失。"
        "23:08時点で両市場の5分変化は売りに逆向き（自己+150、相手+9.75）と既知だった。",
        "",
        "画像は [具体失敗画像一覧](第一巡の具体失敗画像.json)。全経路3枚と判断時まで3枚を実際に表示して確認した。"
        "価格線は1分端の直前気配であり、足中の全更新を表示するローソク足ではない。"
        "注文印は秒単位の原行価格なので線とずれる場合がある。",
        "",
        "## 各手法・商品で赤字上位三場",
        "",
        "表の時刻は、その場で最大損失だった親の新規→返済。詳しい全注文はJSONにある。",
        "",
        "|手法|商品|セッション|場収支|最大損失親：新規→返済|親収支|",
        "|---|---|---|---:|---|---:|",
    ]
    for w in data["worst"]:
        r = min(w["parents"], key=lambda x: x["net"])
        order = ("買い" if r["side"] > 0 else "売り")+str(r["entry"])+" → "+str(r["exit"])
        times = r["entrytime"][5:19]+" → "+r["exittime"][5:19]
        lines.append("|"+w["method"]+"|"+w["symbol"]+"|"+w["session"]+"|"+money(w["net"])+"|"
                     +times+" "+order+"|"+money(r["net"])+"|")
    lines += [
        "",
        "## 除けばよい、では済まない反証",
        "",
        "- 同方向再参加を全部禁止すると、R09日経の81親45勝・+23,180円の群を消す。"
        "前回最大順行価格より先で入り直した24親も15勝・+48,720円で、一律の追い禁止は支持されない。",
        "- 追随で自己5分が失効又は相手5分が反対なら見送る条件も、"
        "R05 TOPIXの25親15勝・+47,050円を消す。"
        "- 期限参加でも9/30 TOPIXは17:45:18の4129売り→19:38:08の4121返済で+39,582円。"
        "当時の方向効率0.0294は10/2日経の負けと似ており、低効率だけで負けは決まらない。",
        "- 狭いストップへの単純変更にも反例がある。途中0.5R以上逆行した勝ちが"
        "R05 TOPIXで42親+892,444円、R09日経で42親+314,760円ある。"
        "これは新しい極値破綻退出を採点した数字ではなく、その検証で必ず確認する反例群。",
        "",
        "## 次巡へ提案する二点",
        "",
        "1. **入口を作った押戻り極値の破綻を退出へ接続する**。通常80/81は準備中の極値を建てた後も保持し、"
        "中値がその逆側へ1呼値抜けたら次正常気配で返済。"
        "元の1Rと追尾条件は固定し、追加撤退だけの比較にする。"
        "単にストップ幅を細くするのではなく、入口の根拠が壊れたことへの応答である。"
        "期限82にはその準備極値がないため、同じ条件を偽装して当てはめない。",
        "2. **期限参加にも当時選んだ状態を引き継ぐ**。期限到来を常に追随へ変更する現設計を分離し、"
        "回帰状態なら既知中心からの位置と中心目標、追随状態なら二市場方向を使う。"
        "通常と同じ枚数・全場参加を保ち、方向/出口の接続だけを比較する。",
        "",
        "どちらも改善は未確定。保存取引の悪い群を単に消した額を新成績と呼ばず、"
        "新経路・新しい再参加・消える勝ちを含めて固定条件で評価する必要がある。",
        "",
        "根拠：[全1,245親と分類](第一巡の夜間入口と順行反復の全親診断.json)。"
        "時間区分は新規時点への親帰属であり、実際にその時間帯に生じた値洗い増減とは区別している。",
    ]
    target = HERE / "第一巡夜間の三段階原因と次巡案.md"
    assert not target.exists()
    target.write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(target.as_posix(), flush=True)


if __name__ == "__main__":
    main()
