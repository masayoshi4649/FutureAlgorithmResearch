"""第一巡を変えず、第二巡の12手法を追加の定義資料として公開する。"""
from pathlib import Path
import shutil
from control164r2 import ROOT,CONFIGS,configs,verify_receipt


def main() -> None:
    """登録済み定義の指紋を確認し、新規ファイルに保存する。

    引数: なし。返り値: None。第一巡資料の上書きと金融再生はしない。
    """
    verify_receipt()
    out=ROOT/"アルゴリズム調査/00164_J02の日中改修と夜間の独立入口"
    target=out/"手法定義164r2.json"
    assert not target.exists()
    shutil.copyfile(CONFIGS,target)
    rows=[f"|`{c['id']}`|{dict(Day='日中',PreUS='米国前',PostUS='米国後')[c['scope']]}|{c['description']}|" for c in configs()]
    doc="""# 第二巡の手法ID

第一巡の20手法を変更せず、下記12手法を別IDで追加した。日中・米国前・米国後の一つの定義に一つのIDを割り当てる。

|ID|対象|簡単な説明|
|---|---|---|
"""+"\n".join(rows)+"""

最大買い100マイクロ・売り100マイクロ（各mini10枚相当）。手数料0、ラージの次正常板で買いAsk／売りBidを使用。通常のJ02・P05・D07の新規判断を土台に、実際に約定した玉の建値で保護する。独自の頻繁な再エントリーは追加していない。

日中13以降の上限は、最初に決めた希望量から、待機後の支持上昇だけを理由に膨らませない条件。弱化や元手法の部分返済があれば減らす。買う前から必ず少量にする条件ではない。

夜間05以降の残玉保護は、元の部分返済に対応した実返済が黒字だった場合だけ。06以降は、最初の注文量が20マイクロ以下の小量初回玉を早く保護し、追加玉は50円逆行で閉じる。07は失速時だけ最長30秒待つ。支持や再加速を校正された勝率とは呼ばない。

時間割は[第一巡の時間割](手法IDと時間割.md#時間割)と同じ。日中・夜前・夜後の合算を一つの手法IDへ変更しない。

第二巡は第一巡の全54場を確認した後の追加開発であり、独立した未見検証ではない。売買ごとの判断に未来の板は使っていない。詳しい事前条件は[計画164r2](../../work/research164/r2/計画164r2.md)、機械可読な固定値は[手法定義164r2.json](手法定義164r2.json)。
"""
    with (out/"第二巡の手法ID.md").open("x",encoding="utf-8") as f:
        f.write(doc)
    print("第二巡12定義を別ファイルへ公開。第一巡は不変です。")


if __name__ == "__main__":
    main()
