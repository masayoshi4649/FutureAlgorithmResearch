def append(name: str, anchor: str, title: str, body: str) -> None:
    """
    機能: 同じ知見を重複させず、正式な出典と測定限界を追記する。
    引数: name(str)は既存分類名、anchor(str)は出典付きアンカー、title(str)は法則名、body(str)は本文。
    返り値: None。過去の知見と元金融源は変更しない。
    """
    path = COMMON / (name + '.md')
    text = path.read_text(encoding='utf-8')
    assert f'id="{anchor}"' not in text, anchor
    text += f'\n\n<a id="{anchor}"></a>\n\n## {title}\n\n{SOURCE}\n\n{body.strip()}\n'
    path.write_text(text, encoding='utf-8')


