def catalog():
    """
    機能: 方向・開始幅・追加停止幅の固定対照を列挙する。
    引数: なし。
    返り値: list[dict]。
    """
    result=[dict(id='C_GU',name='元GU・独立追加なし',relation=0,start_atr=1.,stop_atr=.25,
                 activation_atr=.5,trail_atr=.25,mask=1,time_mode='U',changes={},source_id='E01_G_U')]
    for relation,direction,label in ((1,'F','同方向'),(-1,'H','反対方向')):
        for start,st in ((.5,'05'),(1.,'10')):
            for stop,sp in ((.25,'25'),(.5,'50')):
                result.append(dict(result[0],id=f'C_{direction}{st}_S{sp}',
                    name=f'{label}・{start:g}ATR順行後追加・停止{stop:g}ATR',relation=relation,
                    start_atr=start,stop_atr=stop))
        result.append(dict(result[0],id=f'C_{direction}10_W',name=f'{label}・1ATR順行後追加・緩い独立追尾',
            relation=relation,start_atr=1.,stop_atr=.5,activation_atr=.75,trail_atr=.5))
    assert len(result)==11
    return result


