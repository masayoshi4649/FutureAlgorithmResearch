"""異なる三戦略へ、合計上限以内の固定枚数を配分する。"""

SOURCES = ('GU', 'M3', 'C03')
PRIMARY = 'A0622'


def catalog():
    """
    機能: 損益を使わず、TOPIXの2枚刻みの全配分と半量GU対照を列挙する。
    引数: なし。
    返り値: list[dict]。NKは各配分の2倍、全体で片方向20枚以内。
    """
    result = []
    for gu in range(0, 11, 2):
        for m3 in range(0, 11-gu, 2):
            c03 = 10-gu-m3
            result.append(dict(id=f'A{gu:02d}{m3}{c03}',
                name=f'追従{gu}・中期逆張り{m3}・短期反転{c03}',
                budgets=dict(zip(SOURCES, (gu, m3, c03))), primary=gu==6 and m3==2))
    result.append(dict(id='GU_HALF', name='追従だけ半量の対照',
                       budgets=dict(GU=5, M3=0, C03=0), primary=False))
    assert len(result) == 22 and sum(c['primary'] for c in result) == 1
    assert next(c['id'] for c in result if c['primary']) == PRIMARY
    return result


