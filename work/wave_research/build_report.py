def load(name: str) -> object:
    """機能: 検証済みの保存結果を読み込む。

    引数: name (str) はファイル名。返り値: JSON内容 (object)。
    """
    return json.loads((OUT/name).read_text(encoding="utf-8"))


def rate(values: list) -> str:
    """機能: 未判定を分けた正答率を表示する。

    引数: values (list) は真偽値または未判定。返り値: 件数付き表示 (str)。
    """
    valid = [v for v in values if v is not None]
    return f"{sum(valid)}/{len(valid)}（{100*sum(valid)/len(valid):.1f}%）" if valid else "未判定"


