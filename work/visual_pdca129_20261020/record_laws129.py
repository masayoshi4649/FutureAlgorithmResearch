def main():
    """
    機能: 新規アンカーが存在しない場合だけ、既存知見ファイルへ末尾追記する。
    引数: なし。ENTRIES(dict)に固定した観測済み事象を使う。
    返り値: None。既存項目と過去の金融会計を変更しない。
    """
    folder = ROOT / "アルゴリズム調査/共通/知見台帳"
    count = 0
    for filename, entries in ENTRIES.items():
        path = folder / filename
        text = path.read_text(encoding="utf-8-sig")
        for anchor, body in entries:
            if f'id="{anchor}"' in text:
                continue
            title, rest = body.strip().split("\n", 1)
            text += f'\n\n<a id="{anchor}"></a>\n\n{title}\n\n{SOURCE}\n{rest.replace("__BASE__", BASE)}\n'
            count += 1
        path.write_text(text, encoding="utf-8")
    print("新しい法則を追記", count)


if __name__ == "__main__":
    main()
