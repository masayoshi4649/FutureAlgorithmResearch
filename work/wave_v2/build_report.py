"""第２回の検知結果、指定波の捕捉、板比較と再現手順をまとめる。"""

import json

import pandas as pd

import research_v2 as r


def load(name: str) -> object:
    """機能: 保存済み結果を読む。

    引数: name (str)。返り値: JSON内容 (object)。
    """
    return json.loads((r.OUT/name).read_text(encoding="utf-8"))


def main() -> None:
    """機能: 最終固定結果を日本語の報告書・取引一覧へ書き出す。

    引数: なし。返り値: なし (None)。検知条件を変更しない。
    """
    fixed = load("固定設定.json")
    trades = load("比較_採用取引.json")
    targets = load("比較_採用指定波.json")
    cells = load("比較_採用集計.json")
    current = load("再利用_集計.json")
    table = pd.read_csv(r.OUT/"比較_全条件.csv")
    all_cells = pd.read_csv(r.OUT/"比較_全セル.csv")
    closed = [t for t in trades if t["closed"]]
    wins = sum(t["net_points"]>0 for t in closed)
    lines = ["# 指定された長い波を捉える検知器\n",
"**指定された２日×２銘柄の４波を、全て有意に検知できる候補を実装した。** 採用方式は『短期方向と60分の回帰方向が揃い、相手指数も同方向なら開始。自指数の長期反転が確認されるまで維持』。保存データでは１銘柄・１セッションあたり１〜４回、全12取引を同じセッション内で返済した。\n",
"前回の30分先の正答率中心の探索から評価方法を変更し、指定された長時間の波の捕捉を必須にした。生板の10系統を含む24系統・864設定を同一の保護・約定モデルで比較した。以下は指定例を含む保存データで開発した成績であり、未知データでの正答率の証明ではない。\n",
"## 指定４波での検知と保有\n",
"| 対象の波 | 仮想保有開始→返済 | 指定時間の捕捉率 | 指定区間内の取得値幅 | 参照値幅に対する捕捉率 |\n| --- | --- | ---: | ---: | ---: |"]
    for target in targets:
        begin, end = pd.Timestamp(target["begin"]), pd.Timestamp(target["end"])
        eligible = [t for t in trades if t["session"]==target["session"] and t["symbol"]==target["symbol"] and
                    t["side"]==target["target_side"] and pd.Timestamp(t["entry_time"])<end and pd.Timestamp(t["exit_time"])>begin]
        trade = eligible[0]
        side = "ロング" if target["target_side"]==1 else "ショート"
        a, b = pd.Timestamp(trade["entry_time"]).strftime("%H:%M"), pd.Timestamp(trade["exit_time"]).strftime("%H:%M")
        lines.append(f"| {target['session'][5:10]} {target['symbol']} {side} | {a}→{b} | {target['correct_coverage']*100:.1f}% | {target['captured_points']:+g} | {target['capture_ratio']*100:.1f}% |")
    lines += ["\nNK225の値幅単位は円、TOPIXはポイント。取得値幅は指定時間の中だけを切り出して往復２ティックを控除した評価値で、取引全体の確定損益と区別する。指定区間の逆方向保有は４例とも０分。9月22日の下落開始からは56分遅れるが、その後の指定区間の約61%と、下落値幅の約54%を捉えている。\n",
"判定自体は9月21日が両銘柄11:25、9月22日が両銘柄10:15。判定後１分待ち、次の実在１分足始値で仮想新規とする。9月21日の11:26〜11:28には銘柄によって約定のない分があるため、価格が存在する11:27／11:29が保有開始となる。表では判定時刻と約定時刻を混同しないよう保有開始を示した。\n",
"![指定４波の価格と仮想保有](図_指定４波.png)\n",
"## 採用ルール\n",
f"固定設定は `{r.Config(**fixed['config']).key}`。[実装](research_v2.py)、[設定とハッシュ](固定設定.json)。\n",
"１分足と５分足を組み合わせ、５分足の確定時点で方向を更新する。日付や指定時刻を検知条件へ埋め込んでいない。\n",
"### 新規ロング\n",
"次の全条件を満たす。ショートは方向の符号を全て逆にする。\n",
"1. 自指数の５分足方向指数 `D` が0.15以上。\n"
"2. 自指数の直近20分の終値変化が正。\n"
"3. 自指数の直近60分の１分終値を直線回帰し、回帰線の59分変位が0.5ATR以上、決定係数が0.20以上。\n"
"4. 相手指数の同じ60分回帰が上向きで、決定係数が0.20以上。相手指数にも0.5ATRの大きさを要求するわけではない。\n"
"5. 両指数とも直近の実在価格が10分以内。セッション内に建玉がなく、損切りした同一方向の波が再入禁止状態でない。\n",
"方向指数は、５分足の上昇方向量と下降方向量の大きい正の側だけを残し、それぞれ８期間の指数平均（係数2/9）で平滑化して `D=(上昇量−下降量)/(上昇量＋下降量)` とする。ATRは５分足の真の値幅を係数1/12で平滑化し、最低３本・最低２ティックとする。回帰は60本の１分終値から計算し、無約定分はその時点で既知の終値を持ち越す。価格を補完して仮想約定させることはしない。\n",
"### 継続と返済\n",
"- 新規の厳しい条件が一時的に消えても、その理由だけでは返済しない。自指数の方向指数・20分変化・60分回帰がそろって反対方向になったら返済する。相手指数が反転に追随していなくても返済は行う。反対側の新規は相手指数まで確認できたときだけ。\n"
"- 120分の保有上限は撤廃。セッションが続き方向が崩れなければ数時間保有する。\n"
"- 初期保護幅は開始時ATRの３倍。追跡幅は `４×max(開始時ATR, 現在ATR)`。ロングは保有中の確定１分終値最高値から、ショートは最安値から追跡する。返済価格条件を不利な方向へ緩めない。\n"
"- 保護・追跡返済をした同じ方向には、いったん反対方向の信号が出るまで再入しない。短い往復を同じ波として繰り返し数えないための措置。\n"
"- 日中15:05／夜間翌05:20から新規停止。日中15:35／夜間翌05:50に返済し、それ以降の最初の実在足始値を使う。今回の保存履歴は全12件が同一セッション内に返済済み。夜間の翌日午前は同じ夜間セッションであり、日付変更とセッション跨ぎは区別する。\n"
"- 15:40／翌05:55以後の行を含む入力はエラーにする。返済価格がないことを理由に次セッションの始値を代用しない。途中で終わるスナップショットの未決済は未決済として表示し、返済済みに見せない。実際の注文を出す常駐プログラムは今回起動していない。\n",
"## 指定例以外を含む全保存データの成績\n",
"足の確定後１分遅延、実在足始値・事前保護価格での仮想約定。通常コストは往復２ティック、厳しい条件は往復４ティック。実際の板での並び順・部分約定・手数料実額を再現した成績ではない。\n",
"| セッション | 銘柄 | 検知数 | ２ティック控除後 | ４ティック控除後 | 利益正の割合 |\n| --- | --- | ---: | ---: | ---: | ---: |"]
    for cell in cells:
        lines.append(f"| {cell['session']} | {cell['symbol']} | {cell['count']} | {cell['net_points']:+g} | {cell['stress_points']:+g} | {cell['win_rate']*100:.1f}% |")
    lines += [f"\n全{len(closed)}件のうち利益正は{wins}件（{wins/len(closed)*100:.1f}%）。NK225は計＋1,270円幅、TOPIXは計＋10ポイント。往復４ティックでは＋1,170円幅／＋3ポイント。これらは金額合計ではなく各銘柄の価格差であり、NK225とTOPIXを足していない。TOPIXの夜間は損失が残り、9月22日日中も通常コストで損益ゼロ。４例を捉えたことと、全局面で高精度に売買できることは同一ではない。\n",
"![保存全セッションの全取引](図_保存全セッション.png)\n",
"## 生板からも探した結果\n",
"保存板394,387行を対象に特徴を抽出した。最良売買気配の中心価格、数量加重気配価格、最良気配の注文フロー、１段・５段数量の偏り、約定方向推定出来高、気配の上下更新回数、価格との組合せなど10系統を正式比較へ入れた。単なる５分足指標の置換には限定していない。\n",
"生板内の約定価格と累積出来高から作る『20分の方向付き出来高』は、NK225では指定２波を捉え、１セッション１〜３回に収まる有力候補だった。ただし両銘柄共通では４例を満たさず、最終採用は価格と他指数の長期方向を確認する方式とした。板の数量が偏っていることだけでは、両銘柄に安定して使える方向予測にはならなかった。\n",
"`CurrentPriceTime` は約定時刻で、板更新の受信時刻ではない。同じ約定時刻の板更新群をその時刻へ遡って利用せず、次の異なる約定時刻が現れた時点まで遅らせ、さらに１分枠が確定するまで利用しない。最終の未確定ブロックは破棄する。売側は `Sell1`、買側は `Buy1` を使用した。板の受信遅延自体は復元できない。\n",
"方向付き出来高は価格の上昇・下落から売買方向を推定するティックルールで、実際の成行買い／売りの真値ではない。独立実装で６系列・2,752分を再計算し、出来高増分と符号付き出来高が全分一致、累積出来高の二重計上や次ブロック情報混入は検出しなかった。[板特徴監査](板特徴監査.md)、[方向推定の独立監査](板方向推定監査.md)。\n",
"## 24系統の比較\n",
"各系統36設定。閾値３段階×確認１・３・６分×追跡４・６ATR×反対確認倍率１・３で合計864設定。実際の信号・取引が同一となる組合せもある。下表は各系統の代表で、指定波は２日×２銘柄の４例。全銘柄共通の設定として比較した。\n",
"| 系統 | 指定波合格数 | 最大検知数／セッション | NK225合計値幅 | TOPIX合計値幅 |\n| --- | ---: | ---: | ---: | ---: |"]
    for family, group in table.groupby("family", sort=True):
        best = group.iloc[0]
        aggregate = all_cells[all_cells.config.eq(best.config)].groupby("symbol").net_points.sum()
        lines.append(f"| {family:02d} {best['name']} | {best.target_pass}/4 | {best.max_count} | {aggregate['NK225']:+g} | {aggregate['TOPIX']:+g} |")
    lines += ["\n[全864設定](比較_全条件.csv)、[全設定の指定波評価](比較_指定波.csv)、[全セッション成績](比較_全セル.csv)を保存した。独立した価格探索468設定と持続構造の追加探索も[価格継続改良](価格継続改良.md)に残したが、重複する考え方があるため独立な仮説数として足し上げない。\n",
"合格基準は、指定区間の開始60分以内に20分以上続く同方向保有があり、指定時間の60%以上を同方向で保有し、通常コスト控除後に参照値幅の40%以上を捕捉すること。候補選択は、４波の合格数→各セッション１〜６件→指定区間の逆方向保有を最小化→近傍設定の安定性と全体成績、の順とした。指定例を捉えつつ、同じ区間で逆方向に張る誤検知を減らすよう開発中に評価を精密化した。\n",
"## 感度と未確認部分\n",
"閾値を0.20、0.225、0.25、0.275、0.30へ振った５条件では、指定４波・取引12件・成績が同一だった。追加の執行遅延１・２分でも４例合格を維持した。一方、追加５分では9月22日のショートが61分遅れとなり、時間捕捉57.9%で合格基準を下回る。検知がなくなるわけではないが、この２例の遅延の余裕は大きくない。[感度分析](感度分析.md)。\n",
"保存履歴は日中２回・夜間１回であり、今回指定された日も含め全て開発データである。採用条件や得点をこれらの結果から選んだため、四つの例を満たすことを未知データへの正答率100%とは呼ばない。閾値近傍の再現性は確認したが、より多くの独立セッションでの検証は残る。\n",
"## 前回取得した現在セッションの再利用\n",
"新たなAPI取得は行っていない。前回一度取得した2026年９月23日00:28締切のスナップショットを、固定後に再生した。過去に価格や結果を見ているため、独立した答え合わせではなく既知データの再利用評価である。\n",
"| 銘柄 | 検知／返済済み | 返済済み２ティック控除後 | ４ティック控除後 |\n| --- | ---: | ---: | ---: |"]
    for cell in current:
        lines.append(f"| {cell['symbol']} | {cell['count']}/{cell['closed']} | {cell['net_points']:+g} | {cell['stress_points']:+g} |")
    lines += ["\n両銘柄とも00:28の観測終了時点で１件ずつ未決済。夜間セッションは続いているため、返済予定は同セッション内の05:50。未観測の将来の返済を実績として作らず、含み損益も上表へ入れていない。[再利用取引](再利用_取引.json)。\n",
"## 再現・安全な境界処理\n",
"元の `book`、`candle_1min`、`candle_5min` は変更していない。成果物はこのディレクトリに保存した。既存の前回研究も保持している。\n",
"```powershell\npython -X utf8 work/wave_v2/replay.py\npython -X utf8 work/wave_v2/test_v2.py\n```\n",
"再現コマンドは外部通信なしで入力・コードのハッシュと全採用結果の一致を確認する。価格・板の未来を変える検査、途中切断で過去の判断が変わらない検査、採用設定の18切断点、日中・夜間の返済、同一波の再入抑制などを実施した。境界レビューでは異なるセッションの行を混ぜると跨ぎ返済になり得る入力を見つけ、明示的に拒否する検査を追加した。正常な保存入力の結果は変更前と完全一致している。\n",
"AGENTS.mdで新規の `market` は認められていないため、今回は実注文を発行していない。実注文接続時には `limit`／`stop` の新規条件と約定確認が必要。返済は `market` または事前の保護条件を使い、セッション終了前の残建玉確認を独立した必須処理にする。本検証の終値追跡とAPIの価格極値追跡 `trail` を同じ成績として扱わない。\n"]
    (r.OUT/"検証結果.md").write_text("\n".join(lines), encoding="utf-8")
    pd.DataFrame(trades).rename(columns={"symbol":"銘柄", "session":"セッション", "side":"方向１買い負１売り",
        "entry_time":"仮想保有開始", "exit_time":"仮想返済", "entry_price":"開始価格", "exit_price":"返済価格",
        "net_points":"２ティック控除後値幅", "stress_points":"４ティック控除後値幅", "reason":"返済理由"}).to_csv(r.OUT/"採用_取引一覧.csv", index=False, encoding="utf-8-sig")
    pd.DataFrame(targets).to_csv(r.OUT/"採用_指定波.csv", index=False, encoding="utf-8-sig")
    print("検証結果.md、採用_取引一覧.csv、採用_指定波.csv を保存しました。")


if __name__ == "__main__":
    main()
