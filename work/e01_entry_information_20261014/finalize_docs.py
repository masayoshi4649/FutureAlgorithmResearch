def write(path: Path, content: str) -> None:
    """
    機能: 日本語の文書をUTF-8と改行付きで保存する。
    引数: path(Path)は対象、content(str)は文書本文。
    返り値: None。金融や原入力には触れない。
    """
    path.write_text(content.rstrip() + '\n', encoding='utf-8', newline='\n')


def append_law(name: str, anchor: str, title: str, body: str) -> None:
    """
    機能: 当時条件・実測・限界を伴う法則を当該110出典で重複せず記録する。
    引数: name/anchor/title/body(str)は分類、アンカー、見出し、本文。
    返り値: None。実在する調査と診断へリンクする。
    """
    path = STUDY / '共通/知見台帳' / (name + '.md')
    previous = path.read_text(encoding='utf-8-sig')
    if 'id="' + anchor + '"' in previous:
        return
    source = f'**出典：** [{CURRENT}](../../{CURRENT}/README.md)。'
    proof = (f'根拠：[全場損益](../../{CURRENT}/{TITLE})、'
             f'[具体原因と勝ち反証](../../{CURRENT}/{CAUSE})、'
             '[限定した小結](../../../work/e01_entry_information_20261014/diagnosis/summary/'
             '出来高代理入口の逆行と気配不利及び勝ち反証の小結.json)、'
             '[独立会計](../../../work/e01_entry_information_20261014/audit/owned/'
             '495唯一金融と99同値及び198PRICEの独立小会計監査.json)。')
    write(path, previous.rstrip() + f'\n\n<a id="{anchor}"></a>\n\n## {title}\n\n{source}\n\n{body}\n\n{proof}')


