def append_once(path,marker,body):
    """
    機能: 既存記録を保持して、出典付き新知見を重複なく追記する。
    引数: path(Path)、marker/body(str)は保存先と識別子・本文。
    返り値: None。
    """
    old=path.read_text(encoding='utf-8-sig')
    if marker not in old:path.write_text(old+'\n\n'+marker+'\n'+body.rstrip()+'\n',encoding='utf-8')


