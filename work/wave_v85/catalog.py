"""E01の四つの改修部品を、損益を見る前に全組合せで固定する。"""

PARTS = {
    'G': '入口で両市場のEMA開始条件を再確認',
    'P': '十分伸びた実組利益の半分を保護',
    'D': '両市場の短期逆行を確認して早期半減',
    'C': '同方向2連敗後は方向条件の再成立を待つ',
}
PRIMARY = ['E01', 'E01_G', 'E01_GPDC']
TIME_MODES = {'J': '日中寄付き回避', 'U': '米国現物寄付き回避', 'JU': '両方の寄付き回避'}


def catalog():
    """
    機能: 原版を含む四部品16通りと、主3手法の時間回避9通りを生成する。
    引数: なし。
    返り値: list[dict]。商品別の条件分岐や成績による入替えはしない。
    """
    values = []
    for mask in range(16):
        parts = [name for bit, name in enumerate(PARTS) if mask & (1 << bit)]
        identifier = 'E01' + ('_' + ''.join(parts) if parts else '')
        name = '原E01' if not parts else ('従来改修R01相当' if parts == ['G'] else 'E01改修 ' + '・'.join(parts))
        values.append(dict(id=identifier, name=name, mask=mask, parts=parts, time_mode='', base_id=identifier,
                           description='元の入口・途中半減・段階トレールを維持' if not parts else '。'.join(PARTS[p] for p in parts)))
    original = {v['id']: v for v in values}
    for identifier in PRIMARY:
        for mode, label in TIME_MODES.items():
            values.append(dict(original[identifier], id=identifier+'_'+mode, time_mode=mode,
                name=original[identifier]['name']+'＋'+label,
                description=original[identifier]['description']+'。'+label))
    return values


