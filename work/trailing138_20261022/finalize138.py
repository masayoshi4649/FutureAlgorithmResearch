def append_once(path, marker, text):
    """
    機能: 既存知見を保ちながら新しい法則を一度だけ追加する。
    引数: path(Path)、marker/text(str)は対象と本文。
    返り値: None。
    """
    previous=path.read_text(encoding='utf-8')
    if marker not in previous:path.write_text(previous+'\n\n'+text+'\n',encoding='utf-8')


