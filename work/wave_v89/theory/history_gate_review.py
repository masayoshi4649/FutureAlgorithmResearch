def digest(path):
    """
    機能: 既往の設計と実装を変更せず、読取証拠の内容指紋を作る。
    引数: path(Path)。
    返り値: SHA256(str)。
    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


def allow(past, window=8, threshold=6, minimum=4, reverse=False):
    """
    機能: 人工反例用に、過去の確定親だけから金額利益割合ゲートを評価する。
    引数: past(list[float])、window(int)、threshold(int:十分率)、minimum(int)、reverse(bool)。
    返り値: bool。これは新戦略の収支再生器ではない。
    """
    values = past[-window:]
    if len(values) < minimum:
        return True
    profit = sum(max(value, 0) for value in values)
    loss = sum(max(-value, 0) for value in values)
    if profit + loss == 0:
        return True
    normal = profit * 10 >= threshold * (profit + loss)
    return not normal if reverse else normal


