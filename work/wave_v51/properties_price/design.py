from pathlib import Path
import json

HERE=Path(__file__).resolve().parent


def freeze() -> dict:
    """機能: 状態定義・観測間隔・将来評価を結果閲覧前に固定する。

    引数: なし。返り値: 固定設計(dict)。
    """
    value=dict(目的='戦略損益で手法を選ばず、公開時点で分かる価格過程の状態と、その後の経路の関係を記述・反証する。',
               新規戦略探索=False,閾値最適化=False,注文利益最適化=False,
               観測='各セッション開始を起点とする5分刻み。完了した1分足を開始+120秒で公開する。連続31本で直前30分を測る。',
               現在価格='観測時刻より厳密に前の最後の有効原本行。経過60秒以内。ATRも現在行の確定公開済みキャッシュ。',
               方向='状態分類は30分変化が±0.5ATRを超えるとき±1、それ以外0。',
               効率比='30分の純変化絶対値/同じ30分の1分絶対変化合計。0.2/0.3閾値は先行研究R04等を流用。',
               状態優先順=[
                   dict(状態='両市場逆方向',条件='両市場の30分方向が非ゼロで反対'),
                   dict(状態='同方向高効率',条件='両市場の30分方向が同じ非ゼロ、両市場ER>=0.3'),
                   dict(状態='自市場低効率',条件='自市場ER<=0.2。上の二状態には該当しない'),
                   dict(状態='自市場高効率',条件='自市場ER>=0.3。上の三状態には該当しない'),
                   dict(状態='中間',条件='残り')],
               補助記述=['直前30本の非ゼロ1分変化符号が変わった回数','EMA30からの価格乖離/ATR','二市場ERと方向','5分公開足変化/ATR'],
               評価方向=['直前30分の純変化方向（閾値なし、完全横ばいは除外）','EMA30へ戻る方向（平均線上は除外）'],
               将来=['次15/30/60分末の方向継続/反転/横ばい','方向を基準とした最大順行MFE/最大逆行MAEのATR比','-0.75ATRに先に触れる前に+1.5ATRへ到達した比率、先逆行、両方未到達'],
               将来時計='開始時刻以上、終了時刻未満の原本価格。終了価格も終了直前60秒以内の観測。評価終了がready.limitを超える例は除外。',
               標本='5分観測は重複しており独立件数とは呼ばない。セッション開始+60分、その後60分刻みの非重複起点でも感度比較。',
               期間='全23/先頭10/次9/原因既読4、昼夜別、銘柄別、状態別。真正未見ではない。',
               推論='観測点比率に加え、各セッション比率の中央値・四分位・最小最大を報告。統計的優位や将来再現は断定しない。',
               因果監査='現在特徴は将来足の改変と足の打切りで完全一致。未来は評価ラベルだけに使用。ATR配列の抽出因果監査は既存研究を継承。',
               API取得数=0)
    path=HERE/'事前固定.json'
    if path.exists():assert json.loads(path.read_text(encoding='utf8'))==value
    else:path.write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf8')
    return value


