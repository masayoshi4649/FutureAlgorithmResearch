"""前半だけの確定済み診断から、改修仮説と否定例を短く整理する。"""
from pathlib import Path
import hashlib
import json


HERE = Path(__file__).resolve().parent


def main():
    """
    機能: 取引分解を要約し、未検証の改修仮説を観測事実と分けて保存する。
    引数: なし。
    返り値: None。確定した診断資料は変更しない。
    """
    source = HERE / '初回3代表の方向継続と損失原因.json'
    data = json.loads(source.read_text(encoding='utf-8'))
    rows = []
    for method, products in data['主3商品別'].items():
        for symbol, item in products.items():
            rows.append(dict(
                手法=method, 商品=symbol,
                **{key: item[key] for key in ('取引数', '収支円', '中値進行円', '新規中値差円',
                                              '返済中値差円', '手数料円', '約定時に共同支持消失数')},
                共同支持中の中値進行円=item['状態別継続']['共同支持']['中値変化円'],
                中立を含む間の中値進行円=item['状態別継続']['中立を含む']['中値変化円'],
                支持消失後の待ち秒中央値=item['最初の根拠変化から返済まで']['共同支持が消失']['初回から両反対判断秒中央値'],
                同一自己価格方向内の再参加数=item['再参加']['同一自己価格方向内の再参加']['取引数']))
    cases = []
    for item in data['最悪3組ずつの具体例']:
        case = {key: item[key] for key in ('ID', '手法', '商品', 'セッション', '方向', '新規判断',
                                          '新規約定', '返済判断', '返済約定', '新規価格', '返済価格',
                                          '収支円', '最大清算含み益円', '新規約定時に共同支持あり')}
        case['最初の根拠変化'] = {}
        for event, value in item['最初の根拠変化'].items():
            if value is None:
                continue
            case['最初の根拠変化'][event] = {key: value[key] for key in
                ('時計', 'その時の清算含み損益円', '実返済までの増減円', '両反対判断まで秒')}
        cases.append(case)
    proposals = [
        dict(思想='小さな往復を方向転換と呼びすぎない',
             変更仮説='価格の反転幅、板イベントの集計数を粗くし、同じ方向の中で繰り返し費用を払う回数を抑える。保有時間では制限しない。',
             根拠='D3の前半費用負担は気配差と手数料合計でTOPIX8,023,232円、NK2253,311,960円。D1・D3は中値経路自体も赤字なので費用減だけで黒字になるとは言えない。',
             判定='改修を試す理由はあるが、粗くするほど利益が増えるとは未証明。大きな反転待ちは一回の損失を増やす。'),
        dict(思想='入口の強い確認と、保有を止める方向変化を分ける',
             変更仮説='入口は共同圧力や価格一致を要求し、出口は価格転換を別に監視する。入口時からその価格方向と矛盾する場合は見送る。',
             根拠='D2は新規約定時点で共同支持が消失した取引がTOPIX60/68組、NK22563/79組。X2は有効な中立でも強い両反対を待ち、支持消失からの返済判断中央値は1,382秒・1,238秒。',
             否定例='中立ですぐ降りる既存X0の完全再生ではD3の取引数がTOPIX1,212→4,171組、NK2251,184→4,079組になり、赤字が増えた。単発取引で損失を減らせても、再参加を含む全経路で有利とは限らない。',
             判定='出口を別の価格証拠にする仮説は合理的。ただし利益化、最適反転幅、5秒の発注待ちへの耐性は未検証。'),
        dict(思想='同じ根拠へ機械的に入り直さない',
             変更仮説='早い出口を追加する場合は、一度有効な中立・反対を観測し、再び入口条件が成立するまで同方向の再新規を許可しない。欠測を再準備として扱わない。',
             根拠='既存X2では同一自己価格転換内の同方向再参加は3代表の両商品とも0組。同じ返済行での同方向再参加も最大2組なので、旧損失の主因を再準備不足とは断定できない。',
             判定='新しい早期出口の売買往復を抑える構造として検証する。既存X2の大赤字をこれだけで直せるという証拠はない。')]
    output = dict(
        対象='前16だけ。後14と改修結果は未参照。新しい損益再生は行っていない。',
        確定診断SHA256=hashlib.sha256(source.read_bytes()).hexdigest(),
        要点=[
            '観測済みの圧力と、その後も同方向に動き続けることは別。入口で二市場が一致しても、注文が着くまでに支持が失われることが多い。',
            'D3では支持が続く区間の中値は順行したが、中立を含む区間で反転し、気配差と手数料も重い。支持の定義をそのまま出口に使う欠点がある。',
            'D1は共同支持中の次行中値変化も両商品で赤字。すべてを出口の遅さだけで説明できない。',
            '有効な中立と参照品質不足は分けた。価格時計の停滞だけでは真の情報欠落や通信遅延を断定しない。',
            '最大含み益は後から分かる経路上の値であり、確定利益ではない。最初の警告時点も単発返済診断を新手法の収支として扱わない。'],
        数値=rows, 最悪18組の要約=cases, 次回改修仮説最大3=proposals,
        原本照合=data['原本照合'])
    target = HERE / '診断の要点と次回仮説.json'
    target.write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(dict(保存=str(target), 要約取引数=len(cases), 仮説数=len(proposals)), ensure_ascii=False))


if __name__ == '__main__':
    main()
