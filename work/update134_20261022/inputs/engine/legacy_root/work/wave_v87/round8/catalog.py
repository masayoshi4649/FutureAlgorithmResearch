"""元玉不変のまま、実際の逆行を待って保険を一度だけ建てる十三条件。"""


def catalog():
    """
    機能: 準備幅・逆行幅・二市場確認の固定対照を列挙する。
    引数: なし。
    返り値: list[dict]。
    """
    base=dict(id='I_GU',name='元GU・保険なし',relation=0,prepare_atr=0.,pullback_atr=.25,confirm=0,
        start_atr=0.,stop_atr=.25,activation_atr=.5,trail_atr=.25,mask=1,time_mode='U',changes={},source_id='E01_G_U')
    result=[base]
    for prepare,pa in ((0.,'00'),(.25,'25'),(.5,'50')):
        for pullback,pb in ((.25,'25'),(.5,'50')):
            for confirm in (0,1):
                result.append(dict(base,id=f'I_P{pa}_R{pb}_C{confirm}',relation=-1,
                    name=f'{prepare:g}ATR順行準備・{pullback:g}ATR逆行で保険'+('・双方反対支持' if confirm else '・価格だけ'),
                    prepare_atr=prepare,pullback_atr=pullback,confirm=confirm))
    assert len(result)==13
    return result


