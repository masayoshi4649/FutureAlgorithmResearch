def read_json(name: str) -> dict:
    """機能: 作業フォルダの保存済みJSONを読む。

    引数: name (str) は相対ファイル名。返り値: 内容 (dict)。通信しない。
    """
    return json.loads((OUT / name).read_text(encoding="utf-8"))


def markdown_table(headers: list[str], rows: list[list]) -> str:
    """機能: 比較表を日本語報告へ埋め込める形式にする。

    引数: headers (list[str])、rows (list[list])。返り値: 表 (str)。
    """
    lines = ["|" + "|".join(headers) + "|", "|" + "|".join(["---"] * len(headers)) + "|"]
    return "\n".join(lines + ["|" + "|".join(map(str, row)) + "|" for row in rows])


def target_row(target: dict) -> list:
    """機能: 指定波の検知と実取引の損益を分けて表示する。

    引数: target (dict)。返り値: 表の一行 (list)。
    """
    entry = target["fresh_entry_time"]
    stamp = pd.Timestamp(entry).strftime("%m/%d %H:%M") if entry is not None else "対象となる新規なし"
    return [target["session"], target["symbol"], "買い" if target["target_side"] == 1 else "売り", stamp,
            f'{target["correct_coverage"]:.1%}', f'{target["capture_ratio"]:.1%}',
            f'{target["correct_trade_net_points"]:+g}', "合格" if target["passed"] else "不合格"]


