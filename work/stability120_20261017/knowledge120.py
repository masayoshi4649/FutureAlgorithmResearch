def append(name: str, anchor: str, title: str, body: str) -> None:
    """
    機能: 当時条件・測定対象・限界と既存調査番号付きの出典を追記する。
    引数: name(str)は分類、anchor(str)は00120に属する法則、title(str)は題、body(str)は実測本文。
    返り値: None。同じ法則を二重に追加しない。
    """
    path = COMMON / (name + '.md')
    text = path.read_text(encoding='utf-8')
    assert f'id="{anchor}"' not in text
    text += f'\n\n<a id="{anchor}"></a>\n\n## {title}\n\n{SOURCE}\n\n{body.strip()}\n'
    path.write_text(text, encoding='utf-8')


