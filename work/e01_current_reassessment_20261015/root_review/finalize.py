def replace_once(path: Path,old: str,new: str) -> None:
    """
    機能: 案内の既知の一部分だけを、重複や不一致を検出して置き換える。
    引数: path(Path)、old/new(str) は編集先と既存/新しい文章。
    返り値: None。経済sourceと既存損益は変更しない。
    """
    text=path.read_text(encoding='utf-8')
    assert text.count(old)==1,(str(path),old[:50])
    path.write_text(text.replace(old,new),encoding='utf-8')


