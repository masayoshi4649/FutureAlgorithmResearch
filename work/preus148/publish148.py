def prepend_once(path, marker, text):
    """重複させず新しい案内を先頭へ追加する。

    引数: path(Path)、marker/text(str)。返り値: None。
    """
    old = path.read_text(encoding='utf-8')
    if marker not in old:
        path.write_text(text + '\n\n' + old, encoding='utf-8')


def append_once(path, marker, text):
    """既存知見を保持し、出典付きの新知見を追記する。

    引数: path(Path)、marker/text(str)。返り値: None。
    """
    old = path.read_text(encoding='utf-8')
    if marker not in old:
        path.write_text(old.rstrip() + '\n\n' + text + '\n', encoding='utf-8')


