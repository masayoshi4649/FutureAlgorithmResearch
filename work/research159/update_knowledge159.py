def append_once(path: Path, content: str, marker: str) -> None:
    """既知ファイルの末尾へ重複せず法則を追加する。

    引数: path(Path)、content(str)、marker(str)。返り値: None。
    """
    original = path.read_text(encoding="utf-8-sig")
    assert marker not in original, f"既に記録済み:{path}"
    path.write_text(original.rstrip()+"\n\n"+content.strip()+"\n", encoding="utf-8")


