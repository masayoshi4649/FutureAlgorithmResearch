"""価格を開示しない原本台帳と学習側の入力監査を日本語でまとめる。"""

import json

import data


def main() -> None:
    """機能: 保存された監査結果だけからデータの読む順序と範囲を説明する。

    引数: なし。
    返り値: None: 入力データ監査.mdを書き込む。
    """
    metadata = json.loads((data.OUT/'原本メタ監査.json').read_text(encoding='utf-8'))
    checks = json.loads((data.OUT/'入力対応と足差分の監査.json').read_text(encoding='utf-8'))['検査']
    one_total = sum(r['足と生約定価格の整合']['1分足']['共通足数'] for r in metadata if r['用途'] == '学習候補')
    five_total = sum(r['足と生約定価格の整合']['5分足']['共通足数'] for r in metadata if r['用途'] == '学習候補')
    one_difference = sum(sum(d['間隔分'] == 1 for d in r['足差分']) for r in checks)
    five_difference = sum(sum(d['間隔分'] == 5 for d in r['足差分']) for r in checks)
    lines = [
        '# 入力データ監査', '',
        '最初に本書で対象範囲を確認し、詳細は「原本メタ監査.json」「入力対応と足差分の監査.json」、再現用コードは data.py → audit_data.py の順に読む。', '',
        '今回の原本は７セッション×２銘柄。前６セッションで条件を探索・選択し、9月24日デイは条件固定前には価格解析を行わず、日時・件数・確定フラグ・ファイルハッシュだけ確認した。API取得はこの準備処理では一度も行っていない。', '',
        '| セッション | 銘柄 | 生板原本行数 | 最後の約定時刻 | １分足数 | ５分足数 | 用途 |',
        '|---|---|---:|---|---:|---:|---|',
    ]
    for r in metadata:
        book = r['生板']
        lines.append(f"| {r['セッション']} | {r['銘柄']} | {book['行数']:,} | {book['最後の約定時刻']} | {r['1分足']['行数']} | {r['5分足']['行数']} | {r['用途']} |")
    lines += [
        '', '## 前回からの追加と再利用', '',
        '- 最初の５セッション×２銘柄の生板SHA256は、以前の特徴抽出時のハッシュとすべて一致した。旧特徴を今回の作業先へ複製し、過去の作業先は変更していない。',
        '- 9月23日ナイトは翌05:54まで増えたため、原本から全区間を新しく抽出した。前回API保存分は今回原本の連続部分とバイト単位で完全一致した。原本にはAPI側で省略された寄付き前の状態がNK225で267行、TOPIXで252行先行しているため、単純な行番号同士の比較はしない。',
        '- 9月24日デイは保存監視区間の末尾15:39まである。両銘柄とも足のclosedはすべてtrue。採用条件とソースの固定後だけ prepare(sessions=[HOLDOUT], allow_holdout=True) により価格入力を作る。',
        '', '## 価格と因果性', '',
        f"- 注文監視用の有効生板978,554行について、last/current_priceが原本seq行のCurrentPriceと全行一致することを別走査で検査した。現在価格の欠損は０行。中値への置換・前値補完はしていない。", 
        '- 元の有効板フィルターは維持する。不正気配・時刻欠損・対象セッション外を外し、各行に元原本のseqを保存する。これにより生板原本全行数より約定系列行数は少ない。',
        '- 同一CurrentPriceTimeの連続ブロックから作る方向特徴は、次の異なる取引時刻に進むまで解放しない。全行のCurrentPriceは既存注文の監視に使用できる。受信時刻は記録されていないので、取引時刻と受信時刻の一致までは実証できない。',
        '- 足信号は確定１分足を開始時刻＋２分、ATRは確定５分足を開始時刻＋６分で利用する。２銘柄の信号は他銘柄に追加60秒の待機と180秒の鮮度制約を設ける。',
        '- v11では9月23日ナイトが旧途中データを参照していた。今回は全６セッションに原本足と今回特徴の参照先を明示し、古い部分系列への暗黙参照を除いた。',
        '', '## 保存足と生板再集計の差', '',
        f'学習６セッションで生CurrentPriceを取引時刻の分へまとめてOHLCを再集計すると、１分足は{one_total:,}本中{one_difference}本、５分足は{five_total:,}本中{five_difference}本に差があった。最大差は各銘柄３呼値。すべて始値は一致する。原本の足データは変更せず、そのまま信号材料に使用し、生CurrentPriceは約定監視へ使う。', '',
        '差異は「入力対応と足差分の監査.json」に全件保存した。保存足がどの受信タイミングで確定されたかの情報がないため、差の原因までは断定していない。book・１分足・５分足を完全に同一の価格列とみなす説明は避ける。', '',
        'データの期間は取引監視区間（デイ08:45以上15:40未満、ナイト17:00以上翌05:55未満）を指す。強制返済は別途15:35/05:50に開始するため、セッションを跨いで保有しない。', '',
    ]
    (data.OUT/'入力データ監査.md').write_text('\n'.join(lines), encoding='utf-8')
    print(f'学習の足比較: １分{one_difference}/{one_total}、５分{five_difference}/{five_total}')


if __name__ == '__main__':
    main()
