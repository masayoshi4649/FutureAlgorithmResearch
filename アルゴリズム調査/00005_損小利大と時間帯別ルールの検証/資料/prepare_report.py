def aggregate(frame: pd.DataFrame, by: list[str]) -> list[dict]:
    """機能: 確定利益・損失と勝敗件数から平均利益・平均損失を再計算する。

    引数: frame (DataFrame)、by (list[str])。返り値: 集計結果 (list[dict])。
    """
    columns = ['取引数', '勝ち数', '負け数', '利益円', '損失円', '収支円', '費用倍収支円',
               '最大順行からの返却円', '未返済数', '評価損益円']
    rows = frame.groupby(by, sort=False)[columns].sum().reset_index().to_dict('records')
    for row in rows:
        row['平均利益円'] = row['利益円'] / row['勝ち数'] if row['勝ち数'] else None
        row['平均損失円'] = row['損失円'] / row['負け数'] if row['負け数'] else None
        row['平均利益／平均損失'] = row['平均利益円'] / row['平均損失円'] if row['平均損失円'] and row['平均利益円'] else None
        row['利益合計／損失合計'] = row['利益円'] / row['損失円'] if row['損失円'] else None
    return rows


def comparisons() -> dict:
    """機能: 22対応差分を改善・悪化・不変の割合とセッション差へ分けて表示する。

    引数: なし。返り値: HTML用の比較表 (dict)。
    """
    tests = report.read_json(OUT / '対応差分診断.json')['診断']
    presets = {'入口': catalog.entry_presets(), '出口': catalog.exit_presets(), '時間帯': catalog.time_presets()}
    names = {'入口': 'entry_name', '出口': 'exit_name', '時間帯': 'time_name'}
    result = {}
    for factor in ['入口', '出口', '時間帯']:
        rows = []
        for item in tests:
            if item['因子'] != factor:
                continue
            total, active = item['対応組合せ総数'], item['片方以上取引あり組合せ総数']
            improved, same = item['全対応組合せの改善割合'], item['全対応組合せの不変割合']
            rows.append(dict(変更=presets[factor][item['変更']][names[factor]], 基準=item['基準'],
                             全対応組数=total, 改善率パーセント=100*improved,
                             悪化率パーセント=100*(1-improved-same), 不変率パーセント=100*same,
                             片方以上取引あり組数=active,
                             取引あり組の改善率パーセント=100*item['片方以上取引あり改善割合'],
                             セッション中央値差の合計ATR=item['差合計'],
                             独立セッション候補数=item['セッション数']))
        notes = {
            '入口': '基準E02は0.25ATR反発・鮮度２分・返済後５分休止。費用を往復４tickへ増やした確定ATR収支で比較。鮮度30秒は候補を捨てる変更なので、改善には損失回避と取引減少の両方が含まれます。',
            '出口': '基準X00は初期２ATR・常時２ATR追跡。各出口は初期損切りと追跡開始なども異なるため、単独の短縮だけの効果ではなくルール一式の比較です。',
            '時間帯': '基準Z00は変更なし。完全な夜間は２本だけです。中央値差が０でも改善・悪化する条件はあるため、平均差も次の表に示します。',
        }
        result[factor + 'の対応比較'] = dict(note=notes[factor] + ' 多数の対応組は同じ相場を使っており、独立した検証回数ではありません。', rows=rows)
    session = pd.read_csv(OUT / '対応差分_セッション.csv')
    rows = session[session.因子.eq('時間帯')][['変更', 'セッション', '銘柄', '費用倍ATR差中央値', '費用倍ATR差平均',
                                                   '改善割合', '悪化割合', '不変割合']].to_dict('records')
    result['米国開始前後：夜間別の差'] = dict(note='各入口・出口・信号をそろえ、時間帯処理だけを変えた差です。NY開始窓で１ATRへ短縮するZ03は、２夜間×２銘柄の平均差がすべて負でした。', rows=rows)
    return result


